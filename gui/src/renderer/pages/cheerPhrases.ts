/**
 * gui/src/renderer/pages/cheerPhrases.ts — 「阶段久等」时的激励语（**纯逻辑**）。
 *
 * ── 要解决的体验 ──
 * Agent 跑工具循环 / 等上游首包时，状态行会一直停在同一个阶段（例如「正在调用「读文件」」），
 * 而且**同一个阶段可能是几十秒**。用户原话把两件事同时提了出来：
 *   ① 「实时状态行」不该待在底部监测栏里，应该长在 Agent 输出最下方（已搬到那里）；
 *   ② 某个阶段**进度超 5s** 之后，要"直接替换为带表情包的激励语循环，直到下一阶段"。
 *
 * 于是分工是：
 *   · 状态行（`liveStatus.ts`）负责**说清在做什么**（事实）；
 *   · 本模块负责**阶段久等时的情绪补充**（陪伴），并且只在"已经等太久了"时才出场 ——
 *     它是**奖励/安抚**，不是常驻装饰。
 *
 * ── 为什么独立成模块 ──
 * 触发阈值（5s）、轮换节拍（4s）、以及"哪些句子算内容、哪些算用法说明"都是**可直接回归的规格**。
 * 住在 `.tsx` 里就只能靠肉眼比对，而这里可以逐条断言：
 *   · 阈值必须是 5s（用户点名给的数字）；
 *   · 文案里**不允许出现用法说明**（"Enter 发送 / / 展开指令 / Shift+Enter 换行 / 可拖拽图片"
 *     这类是**产品说明书**，用户在等 Agent 的时候读到它会觉得"你答非所问"）；
 *   · 轮换在任意 seed 下都必须落在合法下标（负数 seed 也不能越界）。
 *
 * ⚠️ 本模块**只做文案与节拍**：不碰 DOM、不碰 React、不自持定时器。
 *   定时器由组件持有（见 ChatPanel 的 `LiveStatusLine`，它自持 1s 时钟、
 *   **只重渲染自己那一小块**——绝不把整面板拖进每秒重渲染）。
 */

/** 阶段停留多久之后开始播激励语（毫秒）。用户点名："进度超 5s"。 */
export const CHEER_AFTER_MS = 5000;

/** 激励语轮换节拍（毫秒）。跟着 1s 时钟走，取 4s ≈ 每 4 个 tick 换一句，读得完又不呆板。 */
export const CHEER_ROTATE_MS = 4000;

/**
 * 激励语气泡池。
 *
 * 收录标准（三条，缺一不可）：
 *   ① **活泼阳光**：正向、有劲、不阴阳怪气；
 *   ② **带表情包**：每句至少一个 emoji / 颜文字 —— 视觉上要一眼看出"这是陪你等的一句闲话"，
 *      而不是又一行系统状态；
 *   ③ **不教用户做事**：不含快捷键、不含输入法提示、不含"你可以……"式引导。
 *      （这正是用户要求"删掉使用说明类激励语"的原因：等 Agent 的时候被教怎么打字，
 *       观感是系统在敷衍。）
 *
 * ⚠️ 新增句子时，`tests/core-ts/a1056-guards.spec.ts` 会检查它是否又被写回"用法说明"
 *    （出现 Enter / Shift / `/` 指令 / 拖拽 等词即判失败）。这是刻意的：这条约束只在
 *    被断言时才守得住。
 */
export const CHEER_PHRASES: readonly string[] = [
  "稍等一下，我在这条路上跑着呢 🏃",
  "别急，好东西值得多等三秒 🍀",
  "正在卖力干活，给你表演个原地起飞 🚀",
  "脑子正在高速转，风扇都快起飞了 🌀",
  "这条路有点长，但我一步没停 🐾",
  "稳住，我保证不摸鱼 🐟❌",
  "咖啡已经备好，我继续冲 ☕",
  "进度条在走，就是有点磨叽 😤",
  "正在把它啃下来，一口一口的那种 🍖",
  "再等等，我在跟工具搏斗 ⚔️",
  "耐心值 +1，回报值 +99 ✨",
  "看起来简单，做起来真的在干活 💪",
  "我还在线，没有卡死，放心 👀",
  "正在慢慢变强，马上就好 🌱",
  "这一小步有点费劲，但值得 🌟",
  "别眨眼，惊喜常常在最后一下 🎁",
  "认真起来我自己都怕 🔥",
  "稍安勿躁，惊喜正在组装中 🧩",
];

/**
 * 阶段停留时间是否已达"该说点什么"的程度。
 *
 * - `< CHEER_AFTER_MS` → false（**故意不给**"3s 就开始催"的选项：太早出场会把状态行挤乱，
 *   且会让"等一会儿"和"等很久"看起来一样）；
 * - 非有限数（NaN / Infinity）→ false（时钟没量到就不播，宁可不播也不乱播）。
 */
export function shouldCheer(stageMs: number): boolean {
  return Number.isFinite(stageMs) && stageMs >= CHEER_AFTER_MS;
}

/**
 * 取一句激励语。`seed` 任意整数（调用方通常传 `Math.floor(stageMs / CHEER_ROTATE_MS)`），
 * 保证**同一阶段内稳定轮换**（不会因为每次渲染随机抖动而闪烁），且越界/负数 seed 也安全。
 */
export function pickCheer(seed: number): string {
  const n = CHEER_PHRASES.length;
  if (!Number.isFinite(seed)) { return CHEER_PHRASES[0]!; }
  const i = ((Math.trunc(seed) % n) + n) % n;
  return CHEER_PHRASES[i]!;
}
