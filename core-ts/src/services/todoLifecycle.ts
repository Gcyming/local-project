/**
 * core-ts/src/services/todoLifecycle.ts — 待办的**生命周期判据**（纯逻辑，唯一出处，A-1066）。
 *
 * 用户明确要求：「当会话结束，待办任务直接自动清除」；追问后口径定为
 * **「本轮跑完即清空」** —— Agent 每次回复**正常跑完**就把该会话的待办清干净。
 * 于是「待办任务」面板的语义变成**本轮进度**：跑完即退场，下一轮重新规划。
 *
 * ⚠️ 用户那句「我很久之前都说过了吧」指向的是**口径被做偏了**：
 *   既有实现只覆盖「全部完成 → 自动清空」（A-980-R32），于是**没做完就被放弃**的清单
 *   （模型改道、需求变了）会永远挂在面板上 —— 那才是用户反复看到的东西。
 *
 * ── 为什么 `error` / `cancelled` 刻意**不清**（与 `done` 分家）──────────────────
 * 这一条是本次实现里最容易做错、也最容易被后人"顺手统一"掉的地方，故写清：
 *
 *  ① `error` —— 本项目有一套**自动续跑**机制（A-968 / A-1051：流意外中断后渲染层带
 *     `resumeSeq` 重连，**续的是同一轮**）。而 `engine.ts` 在**每个工具轮**都会把
 *     `planReminderText(readTodos(sessionId))` 注入模型上下文。若在出错时就清空，
 *     续跑的那一轮会**凭空丢掉计划提醒** —— 用户看到的是"恢复之后它忘了自己要干什么"。
 *     出错不是"本轮跑完"，它是"这一轮还没跑完就被打断了"，所以不清。
 *
 *  ② `cancelled` —— 用户主动中断是"我要接管/改需求"的信号，此时那份清单正是他要接着用的东西；
 *     而且 A-985 早已为这条路径定了口径（把停在"进行中"的项**降级为待办**，而不是删掉）。
 *     在这里删掉会与那条既定设计互相打脸（"中断后清单反而没了"）。
 *
 *  两种情况下清单都不会无限期滞留：下一次**正常跑完**就会清空，滞留长度有界。
 */

/** 一轮 Agent 运行结束的原因 */
export type TurnEndReason =
  /** 正常跑完（流收到 done）—— 用户要的「本轮结束」就是这一种 */
  | "done"
  /** 出错收场（异常 / 上游失败）—— 可能被自动续跑，**不清**（见文件头 ①） */
  | "error"
  /** 用户主动中断（点了停止）—— 清单要接着用，**不清**（见文件头 ②） */
  | "cancelled";

export interface TurnEndInput {
  reason: TurnEndReason;
  /**
   * 该会话此刻**已被另一轮接管**（旧流收尾晚于新流注册 —— 真实存在的竞态，
   * 判据实体见 `gui/src/main/index.ts`：`activeChats.get(cancelKey) !== controller`）。
   *
   * `true` = 盘上这份待办属于**新一轮**，绝不能清。清掉等于把用户刚规划好的清单抹掉
   * （症状："刚规划好，眨眼全没了"）。
   */
  stillActive: boolean;
}

/**
 * 本轮结束 → 是否清空该会话的待办。
 *
 * 判据（顺序即优先级）：
 *   1. `stillActive` → 不清（清单已归属新一轮；这是唯一会误伤的支，必须排在最前）；
 *   2. `reason === "done"` → 清（用户要的"本轮跑完即清空"）；
 *   3. `error` / `cancelled` → 不清（理由见文件头，两条都是"本轮还没跑完"）。
 */
export function shouldClearTodosOnTurnEnd(ev: TurnEndInput): boolean {
  if (ev.stillActive) { return false; }
  return ev.reason === "done";
}
